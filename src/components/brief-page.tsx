import { Link } from '@tanstack/react-router'

import { type BriefRecommendation } from '../domain/brief'
import { type BriefArchiveEntry, type BriefPageData } from '../domain/public-page'
import { RecommendationCard } from './brief-card'
import { BriefHeadlines } from './brief-headlines'
import { Disclaimer } from './disclaimer'
import { formatCalendarDay, nyDateTime } from './ny-time'
import { SitePage } from './site-page'

export const DIRECTION_LABELS = {
  bullish: 'Bullish',
  bearish: 'Bearish',
  neutral: 'Neutral',
} as const satisfies Record<NonNullable<BriefRecommendation['direction']>, string>

function BriefDayLink({ marketDate, label }: { label: string; marketDate: string }) {
  return (
    <Link params={{ date: marketDate }} to="/briefs/$date">
      {label}: <time dateTime={marketDate}>{formatCalendarDay(marketDate)}</time>
    </Link>
  )
}

/**
 * One published brief's own page (`/briefs/$date`): the same trades, theses and headlines the
 * Recommendations view shows for that market date, as text in the document. The thesis goes
 * through the site's Markdown-subset renderer and every other model or third-party string is
 * escaped by React, exactly as on the brief screen.
 */
export function BriefPage({ page }: { page: BriefPageData }) {
  const { brief } = page
  const linked = new Set(page.symbolsWithPages)
  return (
    <SitePage
      intro="The daily options brief for this market date: one trade line and thesis per name, and the morning's headlines."
      title={`Options brief, ${formatCalendarDay(brief.marketDate)}`}
    >
      <section aria-label="About this brief">
        <p className="public-page-meta">
          Market date <time dateTime={brief.marketDate}>{formatCalendarDay(brief.marketDate)}</time>
          {' · published '}<time dateTime={brief.publishedAt}>{nyDateTime.format(new Date(brief.publishedAt))}</time>
          {' · generated by '}{brief.model}
        </p>
        <nav aria-label="Brief archive" className="public-brief-nav">
          {page.olderMarketDate ? <BriefDayLink label="Previous" marketDate={page.olderMarketDate} /> : null}
          {page.newerMarketDate ? <BriefDayLink label="Next" marketDate={page.newerMarketDate} /> : null}
          <Link to="/briefs">All briefs</Link>
          <Link to="/positions">Positions</Link>
        </nav>
      </section>
      {brief.recommendations.length === 0 && <section><h2>No trades</h2></section>}
      {brief.recommendations.map((recommendation, index) => (
        <section className="public-brief-trade" key={`${recommendation.symbol}-${index}`}>
          <h2>
            {linked.has(recommendation.symbol)
              ? <Link params={{ symbol: recommendation.symbol }} to="/options/$symbol">{recommendation.symbol}</Link>
              : recommendation.symbol}
            {recommendation.direction && ` · ${DIRECTION_LABELS[recommendation.direction]}`}
          </h2>
          <RecommendationCard recommendation={recommendation} />
        </section>
      ))}
      <BriefHeadlines links={brief.links} />
      {/* Said once, at the foot of the brief, in the words the brief screen closes on. */}
      <Disclaimer className="public-page-disclaimer" />
    </SitePage>
  )
}

/** The archive index (`/briefs`): every published market date, newest first, with its names. */
export function BriefArchivePage({ briefs }: { briefs: BriefArchiveEntry[] }) {
  return (
    <SitePage
      intro="Every published daily options brief by market date, newest first."
      title="Daily options briefs"
    >
      <section aria-label="Published briefs">
        {briefs.length
          ? (
            <ol className="public-brief-archive">
              {briefs.map((entry) => (
                <li key={entry.marketDate}>
                  <Link params={{ date: entry.marketDate }} to="/briefs/$date">
                    <time dateTime={entry.marketDate}>{formatCalendarDay(entry.marketDate)}</time>
                  </Link>
                  <span>{entry.symbols.length ? entry.symbols.join(', ') : 'No trades'}</span>
                </li>
              ))}
            </ol>
          )
          : <p>No brief has been published yet.</p>}
        <p>
          The latest brief is also in the app under <Link to="/recommendations">Recommendations</Link>, and what it has open
          and closed is under <Link to="/positions">Positions</Link>.
        </p>
      </section>
      <Disclaimer className="public-page-disclaimer" />
    </SitePage>
  )
}
